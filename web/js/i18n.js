const LANGS = ["zh-TW", "zh-CN", "en", "ja"];
const LANG_NAMES = { "zh-TW": "繁體中文", "zh-CN": "简体中文", "en": "English", "ja": "日本語" };
const STORE_KEY = "arena.lang";
const ESC = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
const esc = s => String(s == null ? "" : s).replace(/[&<>"']/g, c => ESC[c]);

// Map any BCP-47 tag to one of the supported languages (or null).
function normLang(tag) {
  if (!tag) return null;
  const x = String(tag).trim().toLowerCase().replace(/_/g, "-");
  if (x === "zh-tw" || x === "zh-hk" || x === "zh-mo" || x.startsWith("zh-hant")) return "zh-TW";
  if (x === "zh" || x === "zh-cn" || x === "zh-sg" || x.startsWith("zh-hans")) return "zh-CN";
  if (x.startsWith("zh-")) return "zh-TW";
  if (x === "en" || x.startsWith("en-")) return "en";
  if (x === "ja" || x.startsWith("ja-")) return "ja";
  return null;
}

function readStored() { try { return localStorage.getItem(STORE_KEY); } catch (_) { return null; } }
function writeStored(v) { try { localStorage.setItem(STORE_KEY, v); } catch (_) { /* storage blocked: URL ?lang= still carries it */ } }

// Detection order: ?lang= → localStorage → navigator.languages → zh-TW
function detect() {
  let fromUrl = null;
  try { fromUrl = normLang(new URLSearchParams(location.search).get("lang")); } catch (_) { /* ignore */ }
  if (fromUrl) return fromUrl;
  const stored = normLang(readStored());
  if (stored) return stored;
  const navs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language];
  for (const n of navs) { const l = normLang(n); if (l) return l; }
  return "en";                      // nothing detected: English (the repo and docs are English-first)
}

let LANG = detect();

function raw(key) {
  const table = STR[LANG] || STR["zh-TW"];
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  if (Object.prototype.hasOwnProperty.call(STR["zh-TW"], key)) return STR["zh-TW"][key];
  return key;
}
// Plain text: use with textContent only. Params are inserted verbatim.
function t(key, params) {
  const s = raw(key);
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}
// HTML: template is trusted (from STR), every param is HTML-escaped.
function th(key, params) {
  const s = raw(key);
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? esc(params[k]) : m)) : s;
}

// Add/replace ?lang= on same-site page links so the choice survives even when storage is blocked.
function keepLangLinks(root) {
  (root || document).querySelectorAll("a.keep-lang").forEach(a => {
    try {
      const u = new URL(a.getAttribute("href"), location.href);
      if (u.origin !== location.origin) return;
      u.searchParams.set("lang", LANG);
      const api = new URLSearchParams(location.search).get("api");
      if (api && !u.searchParams.get("api")) u.searchParams.set("api", api);
      a.href = u.pathname.split("/").pop() + u.search + u.hash;
    } catch (_) { /* leave link as-is */ }
  });
}

function apply(root) {
  const r = root || document;
  r.querySelectorAll("[data-i18n]").forEach(n => {
    const k = n.getAttribute("data-i18n");
    if (n.hasAttribute("data-i18n-html")) n.innerHTML = th(k); else n.textContent = t(k);
  });
  r.querySelectorAll("[data-i18n-placeholder]").forEach(n => { n.placeholder = t(n.getAttribute("data-i18n-placeholder")); });
  r.querySelectorAll("[data-i18n-title]").forEach(n => { n.title = t(n.getAttribute("data-i18n-title")); });
  r.querySelectorAll("[data-i18n-aria]").forEach(n => { n.setAttribute("aria-label", t(n.getAttribute("data-i18n-aria"))); });
  r.querySelectorAll("meta[data-i18n-content]").forEach(n => { n.setAttribute("content", t(n.getAttribute("data-i18n-content"))); });
  keepLangLinks(r);
}

function setLang(l, opts) {
  const n = normLang(l);
  if (!n) return;
  LANG = n;
  writeStored(n);
  document.documentElement.lang = n;
  apply();
  document.querySelectorAll("select.lang-select").forEach(s => { s.value = n; });
  try {
    const u = new URL(location.href);
    if (u.searchParams.get("lang") !== n) { u.searchParams.set("lang", n); history.replaceState(history.state, "", u); }
  } catch (_) { /* ignore */ }
  if (!(opts && opts.silent)) document.dispatchEvent(new CustomEvent("arena:lang", { detail: n }));
}

// Build a <select> language switcher inside `host`.
function mountSwitcher(host) {
  if (!host) return;
  const sel = document.createElement("select");
  sel.className = "lang-select";
  sel.setAttribute("aria-label", t("lang"));
  sel.setAttribute("data-i18n-aria", "lang");
  for (const l of LANGS) {
    const o = document.createElement("option");
    o.value = l; o.textContent = LANG_NAMES[l]; o.lang = l;
    sel.appendChild(o);
  }
  sel.value = LANG;
  sel.addEventListener("change", () => setLang(sel.value));
  host.appendChild(sel);
}

const numFmt = () => new Intl.NumberFormat(LANG, { useGrouping: "min2" });
function fmtNum(n) { const v = Number(n); return Number.isFinite(v) ? numFmt().format(v) : "–"; }
function fmtTime(epochSec) {
  const v = Number(epochSec);
  if (!Number.isFinite(v)) return "–";
  return new Intl.DateTimeFormat(LANG, { hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false }).format(new Date(v * 1000));
}

window.I18N = Object.freeze({
  LANGS, LANG_NAMES, t, th, esc, apply, setLang, mountSwitcher, fmtNum, fmtTime, normLang,
  lang: () => LANG,
  has: key => Object.prototype.hasOwnProperty.call(STR["zh-TW"], key),
});

document.documentElement.lang = LANG;
