def test_party_team_queue_over_http(monkeypatch):
    # TestClient requests all come from the same "testclient": disable the same-network rule to test only the API flow
    monkeypatch.setattr("server.lobby._net_key", lambda ip: "")
    monkeypatch.setattr("server.lobby.MAX_TICKETS_PER_IP", 10)
    with TestClient(app) as c:
        a, b, s1, s2, o = (reg(c, n) for n in ("Lead", "Mate", "Solo1", "Solo2", "Out"))
        party = c.post("/api/lobby/parties", headers=hdr(a)).json()
        code = party["code"]
        assert c.get(f"/api/lobby/parties/{code}", headers=hdr(o)).status_code == 403       # non-members can't see it
        assert c.post(f"/api/lobby/parties/{code}/join", headers=hdr(b)).status_code == 200
        r = c.post("/api/lobby/queue", json={"mode": "quiz", "size": 2}, headers={**hdr(a), "Accept-Language": "en"})
        assert r.status_code == 409 and r.json()["code"] == "party_ffa" and "team" in r.json()["detail"]
        assert c.post("/api/lobby/queue", json={"mode": "quiz", "format": "2v2"}, headers=hdr(b)).json()["code"] == "leader_only"
        assert c.post("/api/lobby/queue", json={"mode": "quiz", "format": "9v9"}, headers=hdr(a)).json()["code"] == "bad_format"
        td = c.post("/api/lobby/queue", json={"mode": "quiz", "format": "2v2"}, headers=hdr(a)).json()
        assert td["format"] == "2v2" and [m["name"] for m in td["members"]] == ["Lead", "Mate"]
        assert c.get("/api/lobby/me", headers=hdr(b)).json()["ticket"]["ticket_id"] == td["ticket_id"]  # teammates can see it too
        t1 = c.post("/api/lobby/queue", json={"mode": "quiz", "format": "2v2"}, headers=hdr(s1)).json()
        t2 = c.post("/api/lobby/queue", json={"mode": "quiz", "format": "2v2"}, headers=hdr(s2)).json()
        assert c.get("/api/lobby/stats").json()["queues"] == {"quiz:2v2": 4}
        rt.lobby.tick()
        for who, tid in ((a, td), (b, td), (s1, t1), (s2, t2)):
            v = c.post(f"/api/lobby/tickets/{tid['ticket_id']}/accept", headers=hdr(who)).json()
        assert v["status"] == "confirmed"
        va = c.get(f"/api/lobby/tickets/{td['ticket_id']}", headers=hdr(a)).json()
        vb = c.get(f"/api/lobby/tickets/{td['ticket_id']}", headers=hdr(b)).json()
        assert "token" not in va and va["side"] == vb["side"]                        # seats go to the agents only
        ta = rt.hub.pending(a["player"]["id"], 0)[-1]
        tb = rt.hub.pending(b["player"]["id"], 0)[-1]
        assert ta["token"] != tb["token"] and ta["match_id"] == tb["match_id"] == va["match_id"] and ta["side"] == va["side"]
        mid = va["match_id"]
        listed = {m["match_id"]: m for m in c.get("/api/lobby/matches").json()["matches"]}
        sides = listed[mid]["sides"]                                                  # spectate list includes sides
        assert sides["Lead"] == sides["Mate"] != sides["Solo1"] == sides["Solo2"]
        rt.matches[mid]["task"].cancel()
        drop_slot(ta["token"])


def test_daily_cap_counts_opponent_pairs_not_whole_lobby():
    rt._pair_counts.clear()
    # Bringing in a third player doesn't get the same opponent pair around it: A and B get at most 3 rated matches per day
    for i in range(3):
        assert rt._ranked_today(["p_a", "p_b", f"p_x{i}"]) is True
    assert rt._ranked_today(["p_a", "p_b", "p_new"]) is False
    # Team match: teammates aren't opponents, so A and B on the same team are not capped
    teams = {"p_a": "red", "p_b": "red", "p_c": "blue", "p_d": "blue"}
    rt._pair_counts.clear()
    for i in range(5):
        t = {**teams, f"p_c{i}": "blue", f"p_d{i}": "blue"}
        assert rt._ranked_today(["p_a", "p_b", f"p_c{i}", f"p_d{i}"], t) is True


def test_rate_limit_is_per_player_with_a_per_ip_cap(monkeypatch):
    # Players behind one home router each get their own budget; the IP as a whole is still capped
    monkeypatch.setitem(guard.RULES, "global", guard.Rule("global", 3, 60))
    monkeypatch.setitem(guard.RULES, "global_ip", guard.Rule("global_ip", 8, 60))
    guard.limiter.reset()
    with TestClient(app) as c:
        a = {"X-Player-Id": "p_aaaaaaaaaa"}
        b = {"X-Player-Id": "p_bbbbbbbbbb"}
        assert [c.get("/api/lobby/stats", headers=a).status_code for _ in range(4)] == [200, 200, 200, 429]
        assert [c.get("/api/lobby/stats", headers=b).status_code for _ in range(3)] == [200, 200, 200]
        # forged ids only add buckets under the same IP cap (8 per window in this test)
        codes = [c.get("/api/lobby/stats", headers={"X-Player-Id": f"p_{i:010d}"}).status_code for i in range(3)]
        assert codes == [200, 429, 429]


