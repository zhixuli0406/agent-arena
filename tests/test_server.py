def test_reap_drops_old_matches_and_transcripts(tmp_path):
    import os
    os.makedirs(rt.RUNS_DIR, exist_ok=True)
    old = os.path.join(rt.RUNS_DIR, "20200101-000000-abcdef.jsonl")
    keep = os.path.join(rt.RUNS_DIR, "notes.jsonl")
    for p in (old, keep):
        open(p, "w").close()
        os.utime(p, (0, 0))
    loop = asyncio.new_event_loop()
    fut = loop.create_future()
    fut.set_result(None)
    rt.matches["20200101-000000-abcdef"] = {"task": fut, "started": 0, "mode": "quiz", "players": []}
    rt.reap(now=10 ** 9)
    loop.close()
    assert "20200101-000000-abcdef" not in rt.matches
    assert not os.path.exists(old) and os.path.exists(keep)       # only files matching the match id format are deleted


def test_private_mode_locks_host_and_cors():
    """Host adapter mode: Host must be local (blocks DNS rebinding) and CORS allows local pages only. Settings are fixed at import time, so this runs in a subprocess."""
    import subprocess
    import sys
    code = (
        "from fastapi.testclient import TestClient\n"
        "from server.app import app\n"
        "c = TestClient(app, base_url='http://127.0.0.1')\n"
        "assert c.get('/api/health').status_code == 200\n"
        "assert c.get('/api/health', headers={'Host': 'evil.example'}).status_code == 400\n"
        "r = c.get('/api/health', headers={'Origin': 'https://claude.ai'})\n"
        "assert 'access-control-allow-origin' not in r.headers\n"
        "r = c.get('/api/health', headers={'Origin': 'http://localhost:5173'})\n"
        "assert r.headers.get('access-control-allow-origin') == 'http://localhost:5173'\n"
    )
    env = {**__import__("os").environ, "ARENA_ALLOW_HOST_ADAPTERS": "1"}
    out = subprocess.run([sys.executable, "-c", code], env=env, capture_output=True, text=True, timeout=60)
    assert out.returncode == 0, out.stderr[-2000:]


