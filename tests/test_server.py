def test_connect_action_validation():
    tok = "tk-action-test"
    rt.valid_tokens.add(tok)
    slot = get_slot(tok)
    try:
        with TestClient(app) as c:
            assert c.post("/api/connect/nope/action", json={"content": "x"}).status_code == 404
            assert c.post(f"/api/connect/{tok}/action", json={"round": "abc", "content": "x"}).status_code == 400
            assert c.post(f"/api/connect/{tok}/action", content=b'{"content":"' + b"a" * 9000 + b'"}',
                          headers={"Content-Type": "application/json"}).status_code == 413
            guard.limiter.reset()                                   # what follows tests the answer queue cap, not the rate limit
            codes = [c.post(f"/api/connect/{tok}/action", json={"round": 1, "content": "x"}).status_code
                     for _ in range(9)]
            assert codes[:8] == [200] * 8 and codes[8] == 429          # the answer queue is capped
            guard.limiter.reset()
            burst = [c.post(f"/api/connect/{tok}/action", json={"round": 1, "content": "x"}).status_code
                     for _ in range(11)]
            assert burst.count(429) >= 1                                  # rate limit of 10 per second per token
            slot.finish()
            guard.limiter.reset()
            assert c.post(f"/api/connect/{tok}/action", json={"round": 1, "content": "x"}).status_code == 410
    finally:
        rt.valid_tokens.discard(tok)
        drop_slot(tok)


